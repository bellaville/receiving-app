// Generates firestore.rules from the receipt field list (src/forms/receipt.ts).
//   npm run gen:rules     -> rewrite firestore.rules
//   npm run check:rules   -> fail if firestore.rules is out of date (runs before every build)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { currentCannabisReceiptForm } from "../src/forms/receipt.ts";
import { allFields, type FieldDef, type ScalarField } from "../src/forms/types.ts";

const RULES_PATH = fileURLToPath(new URL("../firestore.rules", import.meta.url));
const KEY_RE = /^[a-z][a-z0-9_]*$/;

const q = (s: string) => `'${s.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
const list = (xs: string[]) => `[${xs.map(q).join(", ")}]`;
const groupFn = (key: string) => `valid_${key}_row`;

function checkKeys(fields: FieldDef[]) {
  const seen = new Set<string>();
  for (const f of fields) {
    if (!KEY_RE.test(f.key)) throw new Error(`Invalid field key "${f.key}": use lowercase letters, digits, underscores`);
    if (seen.has(f.key)) throw new Error(`Duplicate field key "${f.key}"`);
    seen.add(f.key);
    if (f.type === "group") {
      if (f.minItems < 0 || f.maxItems < f.minItems) throw new Error(`Group "${f.key}": bad minItems/maxItems`);
      checkKeys(f.fields);
    }
  }
}

// "All keys allowed, required keys present, each field valid" for a map named m
function mapChecks(m: string, fields: FieldDef[]): string {
  const allKeys = fields.map((f) => f.key);
  const requiredKeys = fields.filter((f) => f.required || (f.type === "group" && f.minItems > 0)).map((f) => f.key);
  // Optional fields may be absent; when present they must pass their check
  const fieldChecks = fields.map((f) => {
    const c = f.type === "group" ? groupCheck(m, f.key, f.minItems, f.maxItems) : check(f, `${m}.${f.key}`);
    return requiredKeys.includes(f.key) ? `(${c})` : `(!('${f.key}' in ${m}) || (${c}))`;
  });
  return [`${m}.keys().hasOnly(${list(allKeys)})`, `${m}.keys().hasAll(${list(requiredKeys)})`, ...fieldChecks]
    .join("\n        && ");
}

// Rules can't loop over a list, so each row position up to maxItems is checked individually
function groupCheck(m: string, key: string, min: number, max: number): string {
  const l = `${m}.${key}`;
  const rows = Array.from({ length: max }, (_, i) => `(${l}.size() <= ${i} || ${groupFn(key)}(${l}[${i}]))`);
  return [`${l} is list`, `${l}.size() >= ${min}`, `${l}.size() <= ${max}`, ...rows].join("\n          && ");
}

// Rules expression checking one value v
function check(f: ScalarField, v: string): string {
  switch (f.type) {
    case "text":
    case "textarea":
      return `${v} is string && ${v}.size() > 0 && ${v}.size() <= ${f.maxLength}`;
    case "date":
      return `${v} is string && ${v}.matches('^[0-9]{4}-[0-9]{2}-[0-9]{2}$')`;
    case "number": {
      const parts = [f.integer ? `${v} is int` : `(${v} is int || ${v} is float)`];
      if (f.min !== undefined) parts.push(`${v} >= ${f.min}`);
      if (f.max !== undefined) parts.push(`${v} <= ${f.max}`);
      // Max decimal places, with a small tolerance for floating-point error
      if (!f.integer && f.decimals !== undefined) {
        const s = 10 ** f.decimals;
        parts.push(`(${v} is int || math.abs(${v} * ${s} - math.round(${v} * ${s})) < 0.000001)`);
      }
      return parts.join(" && ");
    }
    case "select":
      return `${v} in ${list(f.options)}`;
    case "checkbox":
      return f.required ? `${v} == true` : `${v} is bool`;
  }
}

function generate(): string {
  const form = currentCannabisReceiptForm;
  const fields = allFields(form);
  checkKeys(fields);

  const groupFns = fields.flatMap((f) => f.type !== "group" ? [] : [`
    // One row of "${f.key}"
    function ${groupFn(f.key)}(r) {
      return r is map
        && ${mapChecks("r", f.fields)};
    }
`]).join("");

  return `// GENERATED by scripts/gen-rules.ts from src/forms/receipt.ts. Do not edit by hand:
// change the field list, then run \`npm run gen:rules\`.
rules_version = '2';
service cloud.firestore {
  match /databases/{database}/documents {

    // Verified company Google account
    function isStaff() {
      return request.auth != null
        && request.auth.token.email_verified == true
        && request.auth.token.email.matches('.*@growtown[.]ca$');
    }
${groupFns}
    // Receipt form values, version ${form.version}
    function validReceiptValues(v) {
      return ${mapChecks("v", fields)};
    }

    match /cannabis_receipts/{id} {
      allow read: if isStaff();

      // New receipts only, on the current form version. Update and delete are denied (no rule grants them).
      allow create: if isStaff()
        && request.resource.data.keys().hasOnly(['form_version', 'values', 'created_by', 'created_at'])
        && request.resource.data.keys().hasAll(['form_version', 'values', 'created_by', 'created_at'])
        && request.resource.data.form_version == ${form.version}
        && request.resource.data.values is map
        && validReceiptValues(request.resource.data.values)
        && request.resource.data.created_by == request.auth.token.email
        && request.resource.data.created_at == request.time;
    }
  }
}
`;
}

const rules = generate();
if (process.argv.includes("--check")) {
  const current = readFileSync(RULES_PATH, "utf8").replace(/\r\n/g, "\n");
  if (current !== rules) {
    console.error("firestore.rules is out of date with src/forms/receipt.ts. Run `npm run gen:rules`.");
    process.exit(1);
  }
  console.log("firestore.rules is up to date.");
} else {
  writeFileSync(RULES_PATH, rules);
  console.log(`Wrote firestore.rules for receipt form v${currentCannabisReceiptForm.version}.`);
}
